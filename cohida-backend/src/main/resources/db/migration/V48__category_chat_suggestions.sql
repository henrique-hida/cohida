CREATE TABLE category_chat_suggestions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    question VARCHAR(240) NOT NULL CHECK (length(trim(question)) > 0),
    position INTEGER NOT NULL CHECK (position >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    origin VARCHAR(20) NOT NULL CHECK (origin IN ('DEMO', 'AI', 'ADMIN')),
    CONSTRAINT uk_category_chat_suggestion_position
        UNIQUE (category_id, position)
);

CREATE TRIGGER audit_write AFTER INSERT OR UPDATE OR DELETE
    ON category_chat_suggestions FOR EACH ROW
    EXECUTE FUNCTION audit_row_write();
