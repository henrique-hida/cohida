CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    actor_kind VARCHAR(20) NOT NULL,
    actor_id VARCHAR(40),
    table_name VARCHAR(80) NOT NULL,
    operation VARCHAR(8) NOT NULL,
    record_key JSONB NOT NULL,
    changed_fields TEXT[] NOT NULL,
    before_values JSONB,
    after_values JSONB
);

CREATE INDEX idx_audit_log_target ON audit_log (table_name, occurred_at);
CREATE INDEX idx_audit_log_actor ON audit_log (actor_id, occurred_at);

CREATE FUNCTION audit_row_write() RETURNS TRIGGER AS $$
DECLARE
    old_row JSONB := CASE WHEN TG_OP = 'INSERT' THEN '{}'::jsonb
                          ELSE to_jsonb(OLD) END;
    new_row JSONB := CASE WHEN TG_OP = 'DELETE' THEN '{}'::jsonb
                          ELSE to_jsonb(NEW) END;
    source_row JSONB := CASE WHEN TG_OP = 'DELETE' THEN old_row ELSE new_row END;
    fields TEXT[];
    old_safe JSONB;
    new_safe JSONB;
    row_key JSONB;
BEGIN
    SELECT array_agg(key ORDER BY key) INTO fields FROM (
        SELECT COALESCE(o.key, n.key) AS key
        FROM jsonb_each(old_row) o FULL JOIN jsonb_each(new_row) n USING (key)
        WHERE o.value IS DISTINCT FROM n.value
    ) changes;
    IF fields IS NULL THEN RETURN NULL; END IF;

    SELECT COALESCE(jsonb_object_agg(key, value), '{}'::jsonb) INTO row_key
    FROM jsonb_each(source_row)
    WHERE key = 'id' OR key = 'event_id' OR key LIKE '%\_id' ESCAPE '\';

    SELECT jsonb_object_agg(key, CASE
        WHEN key ~* '(password|secret|token|cpf|email|phone|birth|street|zip|'
                   'neighborhood|address|question|response|answer|prompt|'
                   'message|description|idempotency_key|request_hash)'
          OR (TG_TABLE_NAME IN ('customers', 'admins', 'chat_profile',
              'chat_preferences', 'chat_interests') AND key = 'name')
        THEN to_jsonb('[REDACTED]'::text) ELSE value END)
      INTO old_safe FROM jsonb_each(old_row) WHERE key = ANY(fields);
    SELECT jsonb_object_agg(key, CASE
        WHEN key ~* '(password|secret|token|cpf|email|phone|birth|street|zip|'
                   'neighborhood|address|question|response|answer|prompt|'
                   'message|description|idempotency_key|request_hash)'
          OR (TG_TABLE_NAME IN ('customers', 'admins', 'chat_profile',
              'chat_preferences', 'chat_interests') AND key = 'name')
        THEN to_jsonb('[REDACTED]'::text) ELSE value END)
      INTO new_safe FROM jsonb_each(new_row) WHERE key = ANY(fields);

    INSERT INTO audit_log (actor_kind, actor_id, table_name, operation,
        record_key, changed_fields, before_values, after_values)
    VALUES (COALESCE(NULLIF(current_setting('cohida.actor_kind', true), ''),
                     'DATABASE'),
            NULLIF(current_setting('cohida.actor_id', true), ''),
            TG_TABLE_NAME, TG_OP, row_key, fields, old_safe, new_safe);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE target RECORD;
BEGIN
    FOR target IN SELECT tablename FROM pg_tables
        WHERE schemaname = current_schema()
          AND tablename NOT IN ('audit_log', 'flyway_schema_history')
    LOOP
        EXECUTE format('CREATE TRIGGER audit_write AFTER INSERT OR UPDATE OR '
            'DELETE ON %I.%I FOR EACH ROW EXECUTE FUNCTION audit_row_write()',
            current_schema(), target.tablename);
    END LOOP;
END;
$$;
