ALTER TABLE cohida.products
    ADD COLUMN rating_sum NUMERIC(8, 1) NOT NULL DEFAULT 0,
    ADD COLUMN review_count INTEGER NOT NULL DEFAULT 0,
    ADD CONSTRAINT ck_products_review_count CHECK (review_count >= 0);

CREATE TABLE cohida.product_reviews
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP    NOT NULL,
    updated_at  TIMESTAMP    NOT NULL,
    deleted_at  TIMESTAMP,
    product_id  BIGINT       NOT NULL REFERENCES cohida.products (id),
    customer_id BIGINT REFERENCES cohida.customers (id),
    order_id    BIGINT REFERENCES cohida.orders (id),
    rating      NUMERIC(2, 1) NOT NULL,
    description VARCHAR(1000) NOT NULL,
    verified_purchase BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_product_reviews_rating CHECK (rating >= 0 AND rating <= 5 AND rating * 2 = floor(rating * 2)),
    CONSTRAINT uk_product_reviews_customer_product UNIQUE (customer_id, product_id)
);

CREATE INDEX ix_product_reviews_product_created ON cohida.product_reviews (product_id, created_at DESC);
