ALTER TABLE cohida.cart_items ADD COLUMN expiry_warning_sent BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE cohida.expired_cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES cohida.customers (id),
    variant_id BIGINT NOT NULL REFERENCES cohida.product_variants (id),
    quantity INTEGER NOT NULL,
    expired_at TIMESTAMP NOT NULL,
    acknowledged_at TIMESTAMP
);

CREATE INDEX ix_expired_cart_items_customer ON cohida.expired_cart_items (customer_id, expired_at DESC);
